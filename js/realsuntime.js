    /**
     * 计算时间差
     *
     * @param paramString 时间差
     * @param cal 当前时间
     * @return 返回计算好的时间
     */
    function getlocaltime(paramString, cal) {
        var returnCalendar = new Date(cal.getYear()+1900, cal.getMonth(), cal.getDate(), cal.getHours(), cal.getMinutes(), cal.getSeconds());
        var str = paramString.substring(0, 1);
        var arrayOfString = paramString.substring(1).split(":");
        var n;
        if (arrayOfString.length == 3)//地区时间差存在小时
        {
            n = 3600 * parseInt(arrayOfString[0]) + 60 * parseInt(arrayOfString[1]) + parseInt(arrayOfString[2]);

        } else//日期 时间差只有分钟
        {
            n = 60 * parseInt(arrayOfString[0]) + parseInt(arrayOfString[1]);
        }

        if (str=="+") {
            returnCalendar.setSeconds(cal.getSeconds()+n);
        } else {
            returnCalendar.setSeconds(cal.getSeconds()+(n*-1));
        }
        return returnCalendar;
    }

