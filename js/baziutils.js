/**
 * 计算命卦
 * @param year 公历年份
 * @param isman 性别
 */
function minggua(year, isman) {
	// 取年份后两位
	let y = year % 100;
	let num;

	if (isman) {
		// 男：100 - 年份后两位
		num = 100 - y;
		num = num % 9;
		if (num === 0) num = 9;
	} else {
		// 女：年份后两位 + 5
		num = y + 5;
		num = num % 9;
		if (num === 0) num = 9;
	}

	// 命卦对应表
	const guaMap = {
		1: "坎",
		2: "坤",
		3: "震",
		4: "巽",
		5: isman ? "坤" : "艮", // 特殊规则
		6: "乾",
		7: "兑",
		8: "艮",
		9: "离",
	};

	return guaMap[num];
}

