/**
 * 根据年份获取六十甲子干支纪年。
 * @param {int} year 
 * @returns 
 */
function getGanzhiYear(year) {
	// 基准年：甲子年对应的公历年
	const baseYear = 1984; // 甲子年是1984年
	const cycleLength = 60; // 六十甲子的周期

	// 计算年份差距
	let offset = year - baseYear;

	// 使用模运算来找到循环内的偏移
	// 对于负数年份，我们也可以正确找到对应的六十甲子年
	offset = ((offset % cycleLength) + cycleLength) % cycleLength;

	// 计算天干和地支的索引
	const ganIndex = offset % 10;
	const zhiIndex = offset % 12;

	// 返回对应的六十甲子年名称
	return GAN[ganIndex] + ZHI[zhiIndex];
}

/**
 * 验证日期时间参数的有效性
 * @param {number} year 年
 * @param {number} month 月
 * @param {number} day 日
 * @param {number} hour 时
 * @param {number} minute 分
 * @param {number} second 秒
 * @returns {boolean} 日期时间是否有效
 */
function isValidDateTime(year, month, day, hour, minute, second) {
	if (year < 1 || year > 9999) {
		return false;
	}
	if (month < 1 || month > 12) {
		return false;
	}
	if (day < 1 || day > 31) {
		return false;
	}
	if (hour < 0 || hour > 23) {
		return false;
	}
	if (minute < 0 || minute > 59) {
		return false;
	}
	if (second < 0 || second > 59) {
		return false;
	}
	return true;
}


